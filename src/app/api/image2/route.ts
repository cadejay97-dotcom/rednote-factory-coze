function extractImageUrl(data: unknown): string | null {
  if (!data || typeof data !== 'object') return null;
  const record = data as Record<string, unknown>;

  const directKeys = ['image_url', 'imageUrl', 'url', 'output_url'];
  for (const key of directKeys) {
    if (typeof record[key] === 'string') return record[key] as string;
  }

  const arrays = ['data', 'images', 'output', 'result'];
  for (const key of arrays) {
    const value = record[key];
    if (Array.isArray(value)) {
      for (const item of value) {
        if (item && typeof item === 'object') {
          const itemRecord = item as Record<string, unknown>;
          if (typeof itemRecord.url === 'string') return itemRecord.url;
          if (typeof itemRecord.image_url === 'string') return itemRecord.image_url;
          if (typeof itemRecord.b64_json === 'string') return `data:image/png;base64,${itemRecord.b64_json}`;
        }
        if (typeof item === 'string') return item;
      }
    }
  }

  if (typeof record.b64_json === 'string') return `data:image/png;base64,${record.b64_json}`;
  return null;
}

async function callImage2(prompt: string, referenceImage?: string) {
  const endpoint = process.env.IMAGE2_API_URL;
  if (!endpoint) return null;

  const payload: Image2Payload = {
    model: process.env.IMAGE2_MODEL || 'image2',
    prompt,
    size: process.env.IMAGE2_SIZE || '900x1200',
    response_format: 'url',
  };

  if (referenceImage) {
    payload.image = referenceImage;
    payload.reference_image = referenceImage;
  }

  const headers: Record<string, string> = { 'Content-Type': 'application/json' };
  if (process.env.IMAGE2_API_KEY) headers.Authorization = `Bearer ${process.env.IMAGE2_API_KEY}`;

  const response = await fetch(endpoint, {
    method: 'POST',
    headers,
    body: JSON.stringify(payload),
  });

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(`image2 调用失败：${response.status} ${detail.slice(0, 200)}`);
  }

  const data = await response.json();
  const imageUrl = extractImageUrl(data);
  if (!imageUrl) throw new Error('image2 返回中没有识别到图片 URL 或 base64');
  return imageUrl;
}

export async function POST(request: NextRequest) {
  try {
    const body = (await request.json()) as Image2Request;
    const topic = body.topic?.trim();

    if (!topic) {
      return NextResponse.json({ error: '请提供封面主题' }, { status: 400 });
    }

    const coverStyle = body.coverStyle || '爆款封面';
    const prompt = buildPrompt({
      topic,
      coverStyle,
      content: body.content,
      visualGoal: body.visualGoal,
      referenceImage: body.referenceImage,
    });

    const generatedUrl = await callImage2(prompt, body.referenceImage);
    const imageUrl = generatedUrl || createFallbackSvg(topic, coverStyle, body.content);

    return NextResponse.json({
      imageUrl,
      prompt,
      mode: generatedUrl ? 'image2' : 'local-preview',
      note: generatedUrl
        ? '已通过 IMAGE2_API_URL 桥接真实生图服务。'
        : '未配置 IMAGE2_API_URL，当前返回本地 SVG 预览；配置 IMAGE2_API_URL/IMAGE2_API_KEY 后会调用真实 image2。',
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : '封面生成失败';
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
