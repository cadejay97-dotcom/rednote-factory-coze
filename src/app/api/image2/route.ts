import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';

interface Image2Request {
  topic?: string;
  content?: string;
  coverStyle?: string;
  visualGoal?: string;
  referenceImage?: string;
}

interface Image2Payload {
  model?: string;
  prompt: string;
  image?: string;
  reference_image?: string;
  size: string;
  response_format: string;
}

const STYLE_GUIDE: Record<string, string> = {
  '爆款封面': '小红书爆款封面：大标题强对比、红粉强调色、信息密度中高、第一眼能看懂主题。',
  '干货卡片': '干货教程卡片：清单式排版、重点数字突出、留白清晰、适合图文轮播第一页。',
  '治愈手账': '治愈手账风：暖白背景、便签/胶带/手写感元素、柔和粉红点缀、不要科技感。',
  '专业测评': '专业测评风：对比表格、结论标签、可信赖的产品评测感、干净克制。',
};

function buildPrompt(body: Required<Pick<Image2Request, 'topic' | 'coverStyle'>> & Pick<Image2Request, 'content' | 'visualGoal' | 'referenceImage'>) {
  const referenceInstruction = body.referenceImage
    ? '\n- 用户提供了参考图：请参考其构图、颜色关系、文字层级和整体情绪，但不要照搬具体文字或侵权元素。'
    : '';

  return `为小红书/Rednote 图文矩阵生成一张 3:4 竖版封面图。

主题：${body.topic}
封面风格：${STYLE_GUIDE[body.coverStyle] || STYLE_GUIDE['爆款封面']}
内容要点：${body.content || '根据主题自动提炼 2-4 个视觉卖点'}
视觉目标：${body.visualGoal || '让用户一眼知道这篇笔记能解决什么问题，并愿意点开'}${referenceInstruction}

硬性要求：
- 画面比例 3:4，适合小红书首图封面。
- 中文大标题醒目，最多 12 个字；副标题最多 18 个字。
- 主色使用小红书红 #FF2442 与暖粉 #FF6B81，背景偏暖白 #FAFAFA。
- 圆角卡片、便签、色卡、轻微纸张阴影；不要科技蓝紫渐变，不要 3D 渲染。
- 画面要像可直接发布的封面，不要出现明显 AI 水印、乱码文字或多余英文。
- 如果参考图存在，优先学习它的版式骨架和视觉节奏，再融入当前主题。`;
}

function escapeXml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

